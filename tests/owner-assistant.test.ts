import { describe, it, expect } from "vitest";
import { parseAbsence } from "@/lib/owner-assistant";
const NOW = new Date("2026-11-12T10:00:00Z").getTime();
const r = (t: string) => { const a = parseAbsence(t, NOW); return a.ok ? a.understood : "?" + a.ask.slice(0, 12); };
describe("помощник владельца: понимание дат", () => {
  it("диапазон словами", () => { expect(r("Я заболела с 15 по 17 декабря")).toBe("2026-12-15 — 2026-12-17"); });
  it("диапазон цифрами", () => { expect(r("не буду 15.12-17.12")).toBe("2026-12-15 — 2026-12-17"); expect(r("с 3/12 по 5/12")).toBe("2026-12-03 — 2026-12-05"); });
  it("одна дата, украинский и английский", () => { expect(r("захворіла 20 грудня")).toBe("2026-12-20"); expect(r("sick from 15 to 17 December")).toBe("2026-12-15 — 2026-12-17"); });
  it("через границу года", () => { expect(r("не буду с 2 января")).toBe("2027-01-02"); });
  it("сегодня, завтра, на N дней, на неделю", () => {
    expect(r("я заболела сегодня")).toBe("2026-11-12"); expect(r("завтра меня не будет")).toBe("2026-11-13");
    expect(r("заболела на 3 дня с завтрашнего")).toBe("2026-11-13 — 2026-11-15"); expect(r("заболела на неделю с завтра")).toBe("2026-11-13 — 2026-11-19");
  });
  it("непонятное и неверное не угадывается", () => {
    expect(r("мне плохо")).toMatch(/^\?/); expect(r("31 февраля")).toMatch(/^\?/); expect(r("с 17.12 по 15.12")).toMatch(/^\?/);
  });
});
